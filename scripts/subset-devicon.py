#!/usr/bin/env python
"""Build a 23-glyph subset of the devicon icon font + a trimmed stylesheet.

The full devicon package ships a ~1.46 MB .ttf covering every brand icon, but this
portfolio renders only the 23 classes listed in ICON_CLASSES below. We subset the
font to just those glyphs (output: woff2) and emit a stylesheet that declares the
@font-face, the shared base rule, and one :before + one .colored rule per class.

Source of truth for glyph codepoints and brand colors is the devicon CSS itself
(node_modules/devicon/devicon.min.css), so this never invents a value.

CAVEAT: this list is a hand-maintained snapshot of what the site actually uses.
When you add a new `devicon-*` icon to the portfolio data, add its class here and
re-run this script, otherwise the new glyph will be missing from the subset font.

Run:  python scripts/subset-devicon.py
"""

import re
import sys
from pathlib import Path

from fontTools import subset

# Repo-relative paths. Script lives in scripts/, so repo root is the parent.
ROOT = Path(__file__).resolve().parent.parent
DEVICON_DIR = ROOT / "node_modules" / "devicon"
SRC_CSS = DEVICON_DIR / "devicon.min.css"
SRC_TTF = DEVICON_DIR / "fonts" / "devicon.ttf"
OUT_DIR = ROOT / "src" / "styles"
OUT_WOFF2 = OUT_DIR / "devicon-subset.woff2"
OUT_CSS = OUT_DIR / "devicon-subset.css"

# The 23 classes used by the portfolio (see CAVEAT above). Keep in sync with the
# site data (src/data/portfolio.js). All are rendered with the `colored` modifier.
ICON_CLASSES = [
    "devicon-postgresql-plain",
    "devicon-googlecloud-plain",
    "devicon-mysql-plain",
    "devicon-python-plain",
    "devicon-apachespark-plain",
    "devicon-apacheairflow-plain",
    "devicon-apachekafka-plain",
    "devicon-pandas-plain",
    "devicon-scikitlearn-plain",
    "devicon-matplotlib-plain",
    "devicon-react-original",
    "devicon-typescript-plain",
    "devicon-javascript-plain",
    "devicon-html5-plain",
    "devicon-css3-plain",
    "devicon-tailwindcss-plain",
    "devicon-nodejs-plain",
    "devicon-express-original",
    "devicon-figma-plain",
    "devicon-git-plain",
    "devicon-docker-plain",
    "devicon-jupyter-plain",
    "devicon-vscode-plain",
]


def parse_css(css: str):
    """Return {class: codepoint} and {class: '#hex'} parsed from devicon CSS.

    The CSS stores glyphs as literal Private Use Area characters inside
    `content:"..."` (not \\e escapes), and brand colors in `.colored` rules.
    Selectors are comma-joined and aliased, so we scan every devicon- class in
    each rule's selector list and keep the ones we care about.
    """
    wanted = set(ICON_CLASSES)
    codepoints = {}
    colors = {}

    for selectors, glyph in re.findall(r'([^{}]+)\{content:"([^"]*)"\}', css):
        if not glyph:
            continue
        for cls in re.findall(r'devicon-[a-z0-9-]+', selectors):
            # :before selectors only; skip anything that is not a direct class match
            if cls in wanted and cls not in codepoints:
                codepoints[cls] = ord(glyph[0])

    for selectors, hexcolor in re.findall(r'([^{}]+)\{color:(#[0-9a-fA-F]+)\}', css):
        for cls in re.findall(r'devicon-[a-z0-9-]+', selectors):
            if cls in wanted and cls not in colors:
                colors[cls] = hexcolor.lower()

    return codepoints, colors


def build_subset_font(codepoints):
    """Subset the devicon TTF to the given codepoints, write woff2, return size."""
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    unicodes = ",".join(f"U+{cp:04X}" for cp in sorted(codepoints.values()))
    args = [
        str(SRC_TTF),
        f"--unicodes={unicodes}",
        "--flavor=woff2",
        f"--output-file={OUT_WOFF2}",
        # keep the glyphs mapped to their PUA codepoints; drop layout/name cruft
        "--no-hinting",
        "--desubroutinize",
        "--name-IDs=",
        "--notdef-outline",
        "--layout-features=",
    ]
    subset.main(args)
    return OUT_WOFF2.stat().st_size


def build_css(codepoints, colors):
    """Emit the trimmed stylesheet: @font-face + base rule + per-icon rules."""
    selectors = ",".join(f".{c}" for c in ICON_CLASSES)
    before = "".join(
        f'.{c}:before{{content:"\\{codepoints[c]:x}"}}\n' for c in ICON_CLASSES
    )
    colored = "".join(
        f'.{c}.colored{{color:{colors[c]}}}\n' for c in ICON_CLASSES
    )

    css = f"""/* Generated by scripts/subset-devicon.py. Do not edit by hand.
   23-glyph subset of the devicon icon font. Regenerate after adding a devicon icon. */
@font-face {{
  font-family: "devicon";
  src: url("./devicon-subset.woff2") format("woff2");
  font-weight: normal;
  font-style: normal;
  font-display: block;
}}
[class^="devicon-"],
[class*=" devicon-"] {{
  font-family: "devicon" !important;
  speak: never;
  font-style: normal;
  font-weight: normal;
  font-variant: normal;
  text-transform: none;
  line-height: 1;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}}
{before}{colored}"""
    OUT_CSS.write_text(css, encoding="utf-8")


def main():
    css = SRC_CSS.read_text(encoding="utf-8-sig")
    codepoints, colors = parse_css(css)

    missing_cp = [c for c in ICON_CLASSES if c not in codepoints]
    missing_col = [c for c in ICON_CLASSES if c not in colors]
    if missing_cp or missing_col:
        print("ERROR: could not resolve every class from devicon CSS.", file=sys.stderr)
        if missing_cp:
            print(f"  missing codepoint: {missing_cp}", file=sys.stderr)
        if missing_col:
            print(f"  missing color:     {missing_col}", file=sys.stderr)
        sys.exit(1)

    before_size = SRC_TTF.stat().st_size
    after_size = build_subset_font(codepoints)
    build_css(codepoints, colors)

    print(f"Resolved {len(ICON_CLASSES)} icons from devicon CSS.")
    for c in ICON_CLASSES:
        print(f"  {c:<32} U+{codepoints[c]:04X}  {colors[c]}")
    print()
    print(f"Source TTF (full):     {before_size:>9,} bytes ({before_size/1024/1024:.2f} MB)")
    print(f"Subset WOFF2:          {after_size:>9,} bytes ({after_size/1024:.1f} KB)")
    print(f"Reduction:             {100 * (1 - after_size / before_size):.1f}%")
    print(f"Wrote {OUT_WOFF2.relative_to(ROOT)}")
    print(f"Wrote {OUT_CSS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
